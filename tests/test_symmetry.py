"""Point groups, and getting the measurements back onto one coset."""

from __future__ import annotations

import math

import numpy as np
import pytest

from frmony.geometry import random_rotations, relative_angle, rotation_angle
from frmony.symmetry import (
    detect_symmetry,
    point_group,
    residual_angles,
    snap_to_symmetry,
    symmetry_order,
    triangle_residuals,
)


@pytest.fixture
def rng() -> np.random.Generator:
    return np.random.default_rng(5320)


@pytest.mark.parametrize(
    ('name', 'order'),
    [
        ('C1', 1),
        ('C2', 2),
        ('C4', 4),
        ('C7', 7),
        ('D2', 4),
        ('D4', 8),
        ('T', 12),
        ('O', 24),
        ('I', 60),
    ],
)
def test_point_groups_have_the_right_order(name: str, order: int) -> None:
    assert symmetry_order(name) == order
    assert len(point_group(name)) == order


@pytest.mark.parametrize('name', ['C1', 'C3', 'C6', 'D3', 'T', 'O', 'I'])
def test_point_groups_are_groups(name: str) -> None:
    """Closed under multiplication and inverse, with distinct rotations.

    The elements are generated by closure, so this is really a check that
    the closure terminated on a group and not on part of one.
    """
    group = point_group(name)
    np.testing.assert_allclose(group[0], np.eye(3), atol=1e-12)
    np.testing.assert_allclose(np.linalg.det(group), 1.0, atol=1e-12)

    products = np.einsum('aij,bjk->abik', group, group).reshape(-1, 3, 3)
    for product in products:
        distance = np.abs(group - product).max(axis=(1, 2))
        assert distance.min() < 1e-9, f'{name} is not closed'

    # No element appears twice.
    spread = np.abs(group[:, None] - group[None, :]).max(axis=(2, 3))
    np.fill_diagonal(spread, np.inf)
    assert spread.min() > 1e-6


def test_cyclic_groups_turn_about_z() -> None:
    """RELION puts the cyclic axis along z, and interoperating needs that."""
    group = point_group('C4')
    axis = np.array([0.0, 0.0, 1.0])
    for element in group:
        np.testing.assert_allclose(element @ axis, axis, atol=1e-12)

